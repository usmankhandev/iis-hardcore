import pulumi
import ipaddress
import pulumi_aws as aws
import json
import pulumi_random as random
import json
from pathlib import Path




cfg = pulumi.Config()
env = pulumi.get_stack()
project = pulumi.get_project()
prefix = f"{project}-{env}"
account_id = aws.get_caller_identity().account_id


def name(resource: str, component:str = "network") -> str:
    """Naming convention: {project}-{environment}-{component}-{resource}."""
    return f"{prefix}-{component}-{resource}"


# Inputs

vpc_cidr = cfg.require("vpcCidr")
azs = aws.get_availability_zones(state="available").names[:2]

#Derive the subnets from VPC CIDR

subnet_cidrs = [str(n) for n in ipaddress.ip_network(vpc_cidr).subnets(new_prefix=24)][1:3]

# Create VPC

vpc = aws.ec2.Vpc(
    name("vpc"),
    cidr_block=vpc_cidr,
    enable_dns_hostnames=True,
    enable_dns_support=True,
    tags={"Name": name("vpc")},
)

# internet gateway and access

igw = aws.ec2.InternetGateway(
    name("igw"),
    vpc_id=vpc.id,
    tags={"Name": name("igw")},
)

public_route_table = aws.ec2.RouteTable(
    name("public-rt"),
    vpc_id=vpc.id,
    tags={"Name": name("public-rt")},
)

aws.ec2.Route(
    name("public-route"),
    route_table_id=public_route_table.id,
    destination_cidr_block="0.0.0.0/0",
    gateway_id=igw.id,
)

public_subnets = []
for az, cidr in zip(azs, subnet_cidrs):
    subnet = aws.ec2.Subnet(
        name(f"public-subnet-{az}"),
        vpc_id=vpc.id,
        cidr_block=cidr,
        availability_zone=az,
        map_public_ip_on_launch=True,
        tags={"Name": name(f"public-subnet-{az}"), "Tier": "public"},
    )
    aws.ec2.RouteTableAssociation(
        name(f"rta-public-{az}"),
        subnet_id=subnet.id,
        route_table_id=public_route_table.id,
    )
    public_subnets.append(subnet)
    
    
pulumi.export("env", env)
pulumi.export("vpc_id", vpc.id)
pulumi.export("public_subnets", [subnet.id for subnet in public_subnets])
pulumi.export("vpc_cidr", vpc_cidr)
pulumi.export("azs", azs)
pulumi.export("subnet_cidrs", [subnet.cidr_block for subnet in public_subnets])


admin_cidr = cfg.require("adminCidr")
alb_sg = aws.ec2.SecurityGroup(
    name("alb-sg", "security"),
    vpc_id=vpc.id,
    description="Allow HTTP and HTTPS traffic to ALB",
    tags={"Name": name("alb-sg", "security"), "Tier": "security"},
)

web_sg = aws.ec2.SecurityGroup(
    name("web-sg", "security"),
    vpc_id=vpc.id,
    description="Allow HTTP and HTTPS traffic to web servers",
    tags={"Name": name("web-sg", "security"), "Tier": "security"},
)

def rule_in(rule_name, sg, description, **kw):
    aws.vpc.SecurityGroupIngressRule(
        name(rule_name, "security"),
        security_group_id=sg.id,
        description=description,
        **kw
    )

def rule_out_all(rule_name, sg):
    aws.vpc.SecurityGroupEgressRule(
        name(rule_name, "security"),
        security_group_id=sg.id,
        description="Allow all outbound traffic",
        ip_protocol="-1",
        from_port=0,
        to_port=0,
        cidr_ipv4="0.0.0.0/0"
    )



rule_in("alb-http-in", alb_sg, "HTTP from internet", ip_protocol="tcp", from_port=80, to_port=80, cidr_ipv4="0.0.0.0/0")
rule_out_all("alb-out", alb_sg)

rule_in("web-http-from-alb", web_sg, "HTTP from ALB only", ip_protocol="tcp", from_port=80, to_port=80,
        referenced_security_group_id=alb_sg.id)
rule_in("web-rdp-admin", web_sg, "RDP from admin IP", ip_protocol="tcp", from_port=3389, to_port=3389, cidr_ipv4=admin_cidr)
rule_in("web-winrm-admin", web_sg, "WinRM HTTPS (Ansible) from admin IP", ip_protocol="tcp", from_port=5986, to_port=5986,
        cidr_ipv4=admin_cidr)
rule_in("web-intra", web_sg, "Node to node (SQL 1433)", ip_protocol="-1", referenced_security_group_id=web_sg.id)
rule_out_all("web-out", web_sg)

pulumi.export("alb_sg_id", alb_sg.id)
pulumi.export("web_sg_id", web_sg.id)


region = aws.config.region

# secrets: generated by automation and stored once in SSM

def password(rule_name: str) -> random.RandomPassword:
    return random.RandomPassword(
        name(rule_name, "secrets"),
        length=16,
        special=True,
        upper=True,
        lower=True,
        number=True,
    )
    

ansible_password = password("ansible-password")
sql_password = password("sql-password")

ansible_param_name = f"/{project}/{env}/ansible-password"
sql_param_name = f"/{project}/{env}/sql-password"

ansible_param = aws.ssm.Parameter(
    name("ansible-password", "secrets"),
    name=ansible_param_name,
    type="SecureString",
    value=ansible_password.result,
    tags={"Name": name("ansible-password", "secrets")},
)


sql_param = aws.ssm.Parameter(name("sql-password", "secrets"),
    name=sql_param_name,
    type="SecureString",
    value=sql_password.result,
    tags={"Name": name("sql-password", "secrets")},
)

# Identity: what windows servers are allowed to do

web_role = aws.iam.Role(name("web-role", "iam"), assume_role_policy=json.dumps({
    "Version": "2012-10-17",
    "Statement": [{"Effect": "Allow", "Principal": {"Service": "ec2.amazonaws.com"},
                   "Action": "sts:AssumeRole"}],
}))


aws.iam.RolePolicyAttachment(name("ssm-core", "iam"), role=web_role.name, policy_arn="arn:aws:iam::aws:policy/AmazonSSMManagedInstanceCore")



web_profile = aws.iam.InstanceProfile(name("web-profile", "iam"), role=web_role.name)   


pulumi.export("ansible_param_name", ansible_param.name)
pulumi.export("sql_param_name", sql_param.name)
pulumi.export("web_role_name", web_role.name)
pulumi.export("web_profile_name", web_profile.name)    


policy_json = json.dumps({
    "Version": "2012-10-17",
    "Statement": [
        {
            "Effect": "Allow",
            "Action": [
                "ssm:GetParameter"
            ],
            "Resource": (
                f"arn:aws:ssm:{region}:{account_id}:"
                f"parameter{ansible_param_name}"
            )
        }
    ]
})

read_policy = aws.iam.RolePolicy(
    name("read-ansible-password", "iam"),
    role=web_role.id,
    policy=policy_json,
    opts=pulumi.ResourceOptions(
        depends_on=[web_role]
    ),
)


instances_cfg = cfg.require_object("instances")

AMI_PARAMS = {
    "full": "/aws/service/ami-windows-latest/Windows_Server-2022-English-Full-Base",
    "core": "/aws/service/ami-windows-latest/Windows_Server-2022-English-Core-Base"
}

ami_ids = {key: aws.ssm.get_parameter(name=path).value for key, path in AMI_PARAMS.items()}


USER_DATA = (Path(__file__).parent / "userdata" / "bootstrap.ps1").read_text() \
      .replace("__PARAM__", ansible_param_name).replace("__REGION__", region)
      
instances = {}

for spec in instances_cfg:
    roles = spec.get("roles", ["web"])
    inst = aws.ec2.Instance(
        name(spec["name"], "compute"),
        ami=ami_ids[spec.get("image", "full")],
        instance_type=spec["type"],
        subnet_id=public_subnets[spec.get("az", 0)].id,
        vpc_security_group_ids=[web_sg.id],
        iam_instance_profile=web_profile.name,
        user_data=USER_DATA,
        user_data_replace_on_change=True,
        root_block_device=aws.ec2.InstanceRootBlockDeviceArgs(
            volume_size=spec.get("disk_gb", 60), volume_type="gp3", encrypted=True),
        metadata_options=aws.ec2.InstanceMetadataOptionsArgs(http_tokens="required"),
        tags={"Name": name(spec["name"], "compute"), "Roles": ",".join(roles)},
        opts=pulumi.ResourceOptions(ignore_changes=["ami"], depends_on=[read_policy]),
    )
    instances[spec["name"]] = inst


pulumi.export("instances", {
    n: {"id": i.id, "public_ip": i.public_ip, "private_ip": i.private_ip} for n, i in instances.items()
})